/** All particle data types and constants for the Particle Physics Visualizer. */

export type ParticleFamily =
  | "Quark" | "Lepton" | "Gauge Boson" | "Scalar Boson"
  | "Squark" | "Slepton" | "Gaugino" | "Higgsino"
  | "Baryon" | "Meson";

export type Classification = "Fermion" | "Boson";

export type ViewTab = "standard_model" | "supersymmetry" | "hadrons";

export type SortKey =
  | "default" | "name-asc" | "name-desc"
  | "mass-asc" | "mass-desc" | "generation"
  | "charge-asc" | "charge-desc"
  | "spin-asc" | "spin-desc" | "family";

export type FundamentalForce =
  | "Strong"
  | "Electromagnetic"
  | "Weak"
  | "Higgs"
  | "Gravity";

export type VisualArchetype =
  | "quark"
  | "lepton_charged"
  | "neutrino"
  | "photon"
  | "gluon"
  | "weak_boson"
  | "higgs"
  | "baryon"
  | "meson"
  | "squark"
  | "slepton"
  | "gaugino"
  | "higgsino"
  | "gravitino";

export type QuarkColor =
  | "red"
  | "green"
  | "blue"
  | "antired"
  | "antigreen"
  | "antiblue";

export interface QuarkConstituent {
  flavor: "u" | "d" | "c" | "s" | "t" | "b";
  anti: boolean;
  color: QuarkColor;
}

export interface Particle {
  id: string;
  tab: ViewTab;
  name: string;
  symbol: string;
  family: ParticleFamily;
  classification: Classification;
  mass: string;
  massMeV: number | null;
  massQualifier?: "<" | ">";
  charge: string;
  chargeNum: number;
  bipolarCharge?: boolean;
  spin: string;
  spinNum: number;
  description: string;
  generation?: number;
  composition?: string;
  colorCharge: boolean;
  forces: FundamentalForce[];
  meanLifetime: string;
  discovered: string;
  antiparticle: string;
  antiparticleSymbol: string;
  selfConjugate?: boolean;
  superpartnerId?: string;
  quarks?: QuarkConstituent[];
  isSuperposition?: boolean;
  visualArchetype: VisualArchetype;
  archetypeLabel: string;
  hex: string;
  accentHex: string;
}

