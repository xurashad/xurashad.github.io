const QUARK_IDS = ["up", "down", "charm", "strange", "top", "bottom"];
const CHARGED_LEPTON_IDS = ["electron", "muon", "tau"];
const NEUTRINO_IDS = ["electron-neutrino", "muon-neutrino", "tau-neutrino"];
const ALL_SM_FERMION_IDS = [...QUARK_IDS, ...CHARGED_LEPTON_IDS, ...NEUTRINO_IDS];

export function getCoupledParticleIds(particle: Particle): {
  ids: Set<string>;
  summary: string;
} {
  switch (particle.id) {
    case "gluon":
      return {
        ids: new Set([...QUARK_IDS, "gluon"]),
        summary: "Gluon mediates the Strong Force — couples to all 6 color-charged quarks and self-interacts.",
      };
    case "photon":
      return {
        ids: new Set([...QUARK_IDS, ...CHARGED_LEPTON_IDS, "w-boson", "photon"]),
        summary: "Photon mediates Electromagnetism — couples to every electrically charged particle.",
      };
    case "w-boson":
      return {
        ids: new Set([...ALL_SM_FERMION_IDS, "w-boson", "z-boson", "photon", "higgs"]),
        summary: "W± Boson mediates the charged Weak Force — couples to all quarks, leptons, EW bosons, and Higgs.",
      };
    case "z-boson":
      return {
        ids: new Set([...ALL_SM_FERMION_IDS, "w-boson", "z-boson", "higgs"]),
        summary: "Z Boson mediates the neutral Weak Force — couples to all quarks, leptons, W±, and Higgs.",
      };
    case "higgs":
      return {
        ids: new Set([...QUARK_IDS, ...CHARGED_LEPTON_IDS, "w-boson", "z-boson", "higgs"]),
        summary: "Higgs Boson imparts mass via Yukawa & gauge couplings to all massive elementary particles.",
      };
    default: {
      if (particle.family === "Quark") {
        return {
          ids: new Set([particle.id, "gluon", "photon", "w-boson", "z-boson", "higgs"]),
          summary: `${particle.name} Quark feels Strong (g), Electromagnetic (γ), Weak (W±/Z), and Higgs (H) couplings.`,
        };
      }
      if (CHARGED_LEPTON_IDS.includes(particle.id)) {
        return {
          ids: new Set([particle.id, "photon", "w-boson", "z-boson", "higgs"]),
          summary: `${particle.name} feels Electromagnetic (γ), Weak (W±/Z), and Higgs (H) couplings — immune to Strong force.`,
        };
      }
      if (NEUTRINO_IDS.includes(particle.id)) {
        return {
          ids: new Set([particle.id, "w-boson", "z-boson"]),
          summary: `${particle.name} interacts solely via the Weak Force (W± / Z) and Gravity — ghostlike through matter.`,
        };
      }
      return {
        ids: new Set([particle.id]),
        summary: `${particle.name}: ${particle.forces.join(" · ")} interactions.`,
      };
    }
  }
}

/** Map massMeV onto [0, 1] across log10 scale from 0.1 eV (1e-7 MeV) to 10 TeV (1e7 MeV). */
export function getLogMassFraction(massMeV: number | null): number | null {
  if (massMeV === null) return null;
  if (massMeV <= 0) return 0;
  const logVal = Math.log10(massMeV);
  const minLog = -7;
  const maxLog = 7;
  return Math.max(0, Math.min(1, (logVal - minLog) / (maxLog - minLog)));
}

export function formatEffectiveCharge(particle: Particle, effectiveAnti: boolean): string {
  if (!effectiveAnti) return particle.charge;
  if (particle.bipolarCharge) {
    return particle.charge === "±1" ? "∓1" : particle.charge;
  }
  if (particle.charge === "0") return "0";
  if (particle.charge.startsWith("+")) return particle.charge.replace("+", "-");
  if (particle.charge.startsWith("-")) return particle.charge.replace("-", "+");
  return particle.charge;
}

export function formatEffectiveComposition(
  particle: Particle,
  effectiveAnti: boolean,
): string | undefined {
  if (!particle.composition) return undefined;
  if (particle.isSuperposition) return "uū / dd̄ / ss̄ mix";
  if (!effectiveAnti || !particle.quarks || particle.quarks.length === 0) {
    return particle.composition;
  }
  return particle.quarks
    .map((q) => (!q.anti ? `${q.flavor}\u0304` : q.flavor))
    .join("");
}

